// Writes dist/colors.js and its types: every colour token that is a plain hex, as light and dark
// values, read from src/tokens/colors.css and the default (cream) page palette in palettes.css.
// `--rkui-navy-deep` becomes `colors.navyDeep`. Tokens that are mixes (color-mix()) or left unset
// are not included.
import { mkdir, readFile, writeFile } from 'node:fs/promises'

const TOKENS = new URL('../src/tokens/', import.meta.url)
const OUT_DIR = new URL('../dist/', import.meta.url)

/** The `--rkui-*` declarations in `css`, as a map from name (without `--rkui-`) to value. */
function declarations(css) {
  const withoutComments = css.replaceAll(/\/\*[\s\S]*?\*\//g, '')
  const found = new Map()
  for (const [, name, value] of withoutComments.matchAll(/--rkui-([a-z0-9-]+):\s*([^;]+);/g)) {
    found.set(name, value.replaceAll(/\s+/g, ' ').trim())
  }
  return found
}

/** The two halves of `light-dark(a, b)`, split at its top-level comma. */
function lightDarkHalves(value) {
  const inner = value.slice('light-dark('.length, -1)
  let depth = 0
  for (let i = 0; i < inner.length; i++) {
    if (inner[i] === '(') depth++
    if (inner[i] === ')') depth--
    if (inner[i] === ',' && depth === 0) {
      return [inner.slice(0, i).trim(), inner.slice(i + 1).trim()]
    }
  }
  throw new Error(`Can't split ${value}`)
}

/** The hex `value` stands for in the given theme, following var()s; undefined if it isn't one. */
function resolve(value, theme, tokens) {
  if (/^#[0-9a-f]{3,8}$/i.test(value)) return value.toLowerCase()
  const reference = value.match(/^var\(--rkui-([a-z0-9-]+)\)$/)
  if (reference) {
    const target = tokens.get(reference[1])
    return target === undefined ? undefined : resolve(target, theme, tokens)
  }
  if (value.startsWith('light-dark(')) {
    const [light, dark] = lightDarkHalves(value)
    return resolve(theme === 'light' ? light : dark, theme, tokens)
  }
  return undefined
}

/** `navy-deep` as `navyDeep`. */
function camelCase(name) {
  return name.replaceAll(/-([a-z0-9])/g, (_, letter) => letter.toUpperCase())
}

/** Writes dist/colors.js and dist/colors.d.ts. */
export async function buildColors() {
  const colorsCss = await readFile(new URL('colors.css', TOKENS), 'utf8')
  const palettesCss = await readFile(new URL('palettes.css', TOKENS), 'utf8')
  const cream = palettesCss.match(/:root,\s*\[data-palette='cream'\]\s*\{([^}]*)\}/)[1]
  const tokens = new Map([...declarations(cream), ...declarations(colorsCss)])

  const colors = {}
  for (const [name, value] of tokens) {
    const light = resolve(value, 'light', tokens)
    const dark = resolve(value, 'dark', tokens)
    if (light && dark) colors[camelCase(name)] = { light, dark }
  }

  const js = `// Generated by build/colors.js from src/tokens/. Don't edit.\nexport const colors = ${JSON.stringify(colors, null, 2)}\n`
  const types = [
    '// Generated by build/colors.js from src/tokens/.',
    "/** A colour token's hex value in light mode and in dark mode. */",
    'export interface ColorPair {',
    '  light: string',
    '  dark: string',
    '}',
    '/** Every colour token that is a plain hex, by name: `--rkui-navy-deep` is `colors.navyDeep`. */',
    'export declare const colors: {',
    ...Object.keys(colors).map((key) => `  ${key}: ColorPair`),
    '}',
    '',
  ].join('\n')

  await mkdir(OUT_DIR, { recursive: true })
  await writeFile(new URL('colors.js', OUT_DIR), js)
  await writeFile(new URL('colors.d.ts', OUT_DIR), types)
  console.log(`dist/colors.js: ${Object.keys(colors).length} colours`)
}
